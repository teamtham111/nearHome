def source_dicts() -> list[dict[str, object]]:
    return [source.to_dict() for source in SOURCES]


def external_sources() -> tuple[DataSource, ...]:
    return tuple(source for source in SOURCES if source.kind not in {"derived", "platform"})


def by_id(source_id: str) -> DataSource:
    for source in SOURCES:
        if source.id == source_id:
            return source
    raise KeyError(source_id)

