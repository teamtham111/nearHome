"""Canonical inventory of every data source used by NearHomeV2.

Keep this module dependency-free: operators can inspect the inventory even
before the API virtual environment has been installed.  ``run_pipeline.py``
uses the same records for preflight output, and ``docs/data-sources.md``
documents the human-facing lineage.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
from typing import Literal

SourceKind = Literal["user", "official", "commercial", "open", "derived", "platform"]
AccessMode = Literal["request", "scheduled", "offline", "internal"]


