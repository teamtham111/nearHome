    id: str
    name: str
    owner: str
    kind: SourceKind
    access: AccessMode
    authority: str
    endpoint_or_origin: str
    credentials: tuple[str, ...]
    inputs: tuple[str, ...]
    output: str
    consumers: tuple[str, ...]
    cadence: str
    retention: str
    required_for: str

    def to_dict(self) -> dict[str, object]:
        return asdict(self)


